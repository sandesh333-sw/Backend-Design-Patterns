/**
 * Multiplexing and Demultiplexing
 *  Multiplexing is the process of combining multiple signals or data streams into one signal over a shared medium. The main purpose of multiplexing is to maximize the utilization of the available bandwidth and to allow multiple users or applications to share the same communication channel efficiently.
 * 
 * Demultiplexing is the reverse process of multiplexing. It involves separating a multiplexed signal back into its original individual signals or data streams. The main purpose of demultiplexing is to ensure that the correct data is delivered to the intended recipient or application.
 * 
 * In the context of computer networks, multiplexing and demultiplexing are commonly used in various protocols and technologies, such as TCP/IP, HTTP/2, and WebSockets, to enable efficient communication between clients and servers.
 * 
 * Pros: Efficient use of bandwidth, allows multiple users/applications to share resources, can improve performance
 * Cons: Complexity in implementation, potential for interference between signals, requires synchronization
 */